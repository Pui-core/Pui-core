// Dedicated Linux Xvfb only. No Windows GUI input and no default user-data profile.
import fs from 'node:fs';
import path from 'node:path';
import {spawn} from 'node:child_process';
import {file,hash,save} from './native.mjs';
const mode=process.argv[2]||'pilot';
const attempt=process.argv[3];
if(!['pilot','full'].includes(mode)||!/^[-a-z0-9]+$/.test(attempt||''))throw Error('Usage: node source/run-capture.mjs pilot|full unique-attempt');
const workspace=process.env.PROJECTP_CAPTURE_WORKSPACE||'/home/pui/tmp/projectp112-capture-20261026';
if(!workspace.startsWith('/home/pui/'))throw Error('Capture workspace must be on the owned Linux filesystem');
const product=path.join(workspace,'product');
const out=path.join(workspace,attempt);
const data=path.join(workspace,attempt+'-userdata');
const config=path.join(workspace,attempt+'-config');
const cache=path.join(workspace,attempt+'-cache');
if([out,data,config,cache].some(p=>fs.existsSync(p)))throw Error('Attempt/profile already exists; preserve it and use a new attempt name');
const before=JSON.parse(fs.readFileSync(file('qa/product-source-before.json'),'utf8'));
for(const f of before.files)if(hash(path.join(product,f.file))!==f.sha256)throw Error('Pinned core source changed: '+f.file);
fs.mkdirSync(out,{recursive:true});
const log=fs.openSync(path.join(workspace,attempt+'.log'),'wx');
const driver=file('source/capture.gd');
const args=['-a','-s','-screen 0 1920x1080x24 -nolisten tcp','/home/pui/.local/bin/godot','--path',product,'--rendering-method','gl_compatibility','--audio-driver','Dummy','--fixed-fps','30','--disable-vsync','--resolution','1920x1080','--script',driver,'--','--mode',mode,'--out',out];
const env={...process.env,XDG_DATA_HOME:data,XDG_CONFIG_HOME:config,XDG_CACHE_HOME:cache,PROJECTP_CAPTURE_DATA_ROOT:data,LP_NUM_THREADS:'2',LIBGL_ALWAYS_SOFTWARE:'1'};
const started=new Date().toISOString();
const processHandle=spawn('/usr/bin/xvfb-run',args,{env,stdio:['ignore',log,log]});
const launch={mode,attempt,started,launcherPid:processHandle.pid,exe:'/usr/bin/xvfb-run',args,driverSha256:hash(driver),ownedPaths:{workspace,product,out,data,config,cache},limits:{nativeWallSeconds:mode==='pilot'?90:720,maxFrames:mode==='pilot'?420:5000},status:'RUNNING'};
save('qa/'+attempt+'-launch.json',launch);
console.log(JSON.stringify(launch));
processHandle.on('error',error=>{save('qa/'+attempt+'-launch.json',{...launch,status:'LAUNCH_ERROR',error:error.message});fs.closeSync(log);process.exitCode=1;});
processHandle.on('close',(code,signal)=>{fs.closeSync(log);const changed=before.files.filter(f=>hash(path.join(product,f.file))!==f.sha256).map(f=>f.file);const result={...launch,status:code===0&&changed.length===0?'FINISHED':'FAILED',exitCode:code,signal,finished:new Date().toISOString(),coreFilesChecked:before.files.length,changedCore:changed};save('qa/'+attempt+'-launch.json',result);const receipt=path.join(out,'capture.json');if(fs.existsSync(receipt))fs.copyFileSync(receipt,file('qa/'+attempt+'-capture.json'));console.log(JSON.stringify(result));if(code!==0||changed.length)process.exitCode=1;});
